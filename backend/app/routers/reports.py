"""Report generation & download endpoints (Module 5)."""
import io
import json

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session

from app import models
from app.core.security import get_current_user
from app.database import get_db
from app.schemas.schemas import ReportOut

router = APIRouter(prefix="/reports", tags=["Reports"])


def _build_report_text(user: models.User, prediction: models.PredictionHistory) -> str:
    symptoms = json.loads(prediction.symptoms)
    predictions = json.loads(prediction.all_predictions)
    lines = [
        "=" * 60,
        "  CareBot AI — Health Assessment Report",
        "=" * 60,
        f"Patient: {user.full_name} ({user.email})",
        f"Date: {prediction.created_at.strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        f"Reported symptoms: {', '.join(s.replace('_', ' ') for s in symptoms)}",
        "",
        f"Top prediction: {prediction.top_prediction} ({prediction.confidence}% confidence)",
        f"Risk level: {prediction.risk_level}",
        "",
        "All predictions (top 3):",
    ]
    for p in predictions:
        lines.append(f"  - {p['disease']}: {p['confidence']}%")
    lines += [
        "",
        "-" * 60,
        "DISCLAIMER: This report is generated by an AI system for informational",
        "purposes only. It is not a medical diagnosis. Please consult a licensed",
        "healthcare professional for accurate diagnosis and treatment.",
        "=" * 60,
    ]
    return "\n".join(lines)


@router.get("", response_model=list[ReportOut])
def list_reports(
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    return (
        db.query(models.Report)
        .filter(models.Report.user_id == current_user.id)
        .order_by(models.Report.created_at.desc())
        .all()
    )


@router.post("/generate/{prediction_id}", response_model=ReportOut)
def generate_report(
    prediction_id: int,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    prediction = (
        db.query(models.PredictionHistory)
        .filter(
            models.PredictionHistory.id == prediction_id,
            models.PredictionHistory.user_id == current_user.id,
        )
        .first()
    )
    if not prediction:
        raise HTTPException(status_code=404, detail="Prediction not found.")

    content = _build_report_text(current_user, prediction)
    report = models.Report(
        user_id=current_user.id,
        prediction_id=prediction.id,
        title=f"Health Report — {prediction.top_prediction} — {prediction.created_at.strftime('%Y-%m-%d')}",
        content=content,
    )
    db.add(report)
    db.commit()
    db.refresh(report)
    return report


@router.get("/{report_id}/download")
def download_report(
    report_id: int,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    report = (
        db.query(models.Report)
        .filter(models.Report.id == report_id, models.Report.user_id == current_user.id)
        .first()
    )
    if not report:
        raise HTTPException(status_code=404, detail="Report not found.")

    buf = io.BytesIO(report.content.encode("utf-8"))
    return StreamingResponse(
        buf,
        media_type="text/plain",
        headers={"Content-Disposition": f'attachment; filename="carebot_report_{report_id}.txt"'},
    )
